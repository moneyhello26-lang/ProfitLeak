def translate(text: str) -> str:
    if get_language() != "kk":
        return text
    if text in KK:
        return KK[text]
    # Only a system-generated title prefix changes. The entity is untrusted source data.
    for prefix in TITLE_PREFIXES:
        if text.startswith(prefix + ": "):
            return KK[prefix] + text[len(prefix) :]
    return text


