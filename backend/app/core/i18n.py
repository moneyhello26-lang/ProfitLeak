def select_language(header: str) -> Language:
    supported = []
    for order, entry in enumerate(header.lower().split(",")):
        locale, *options = entry.strip().split(";")
        locale = locale.split("-", 1)[0]
        quality = 1.0
        for option in options:
            if option.strip().startswith("q="):
                try:
                    quality = float(option.strip()[2:])
                except ValueError:
                    quality = 0.0
        if locale in ("ru", "kk") and 0 < quality <= 1:
            supported.append((quality, -order, locale))
    return max(supported)[2] if supported else "ru"


