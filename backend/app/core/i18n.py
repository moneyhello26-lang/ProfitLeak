def localize_payload(value, field: str = ""):
    if get_language() == "ru":
        return value
    if isinstance(value, dict):
        result = {
            key: item if key in {"input", "ctx"} else localize_payload(item, key)
            for key, item in value.items()
        }
        if "msg" in value and "loc" in value:
            validation = VALIDATION_MESSAGES.get(value.get("type"))
            if validation:
                try:
                    result["msg"] = validation.format(**value.get("ctx", {}))
                except KeyError:
                    pass
        return result
    if isinstance(value, list):
        return [localize_payload(item, field) for item in value]
    if isinstance(value, str) and field in TEXT_FIELDS | TEXT_LISTS:
        return translate(value)
    return value


Model = TypeVar("Model", bound=BaseModel)


def localized_model(model: Model) -> Model:
    return (
        type(model).model_validate(localize_payload(model.model_dump()))
        if get_language() == "kk"
        else model
    )


class LanguageMiddleware:
    """Context propagates to FastAPI's sync workers and resets after every request."""

    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope["type"] != "http":
            return await self.app(scope, receive, send)
        headers = dict(scope.get("headers", []))
        selected = select_language(headers.get(b"accept-language", b"").decode("latin-1"))
        token = language.set(selected)
        start = None
        chunks = bytearray()

        async def localized_send(message):
            nonlocal start
            if message["type"] == "http.response.start":
                response_headers = list(message.get("headers", []))
                response_headers.append((b"content-language", selected.encode("ascii")))
                # Preserve CORS's Vary header rather than replacing it.
                response_headers.append((b"vary", b"Accept-Language"))
                message = {**message, "headers": response_headers}
                is_json = any(
                    key.lower() == b"content-type" and b"application/json" in value.lower()
                    for key, value in response_headers
                )
                if selected == "kk" and is_json:
                    start = message
                    return
            elif message["type"] == "http.response.body" and start is not None:
                chunks.extend(message.get("body", b""))
                if message.get("more_body", False):
                    return
                try:
                    payload = localize_payload(json.loads(chunks))
                    encoded = json.dumps(
                        payload, ensure_ascii=False, separators=(",", ":")
                    ).encode()
                except (ValueError, UnicodeDecodeError):
                    encoded = bytes(chunks)
                start["headers"] = [
                    (key, value)
                    for key, value in start["headers"]
                    if key.lower() != b"content-length"
                ] + [(b"content-length", str(len(encoded)).encode("ascii"))]
                await send(start)
                await send({**message, "body": encoded})
                start = None
                return
            await send(message)

        try:
            await self.app(scope, receive, localized_send)
        finally:
            language.reset(token)
